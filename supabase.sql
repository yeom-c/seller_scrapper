-- 7. 새로운 사용자가 추가될 때 실행될 함수를 생성합니다.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  trial_permission_id uuid;
  trial_duration_seconds int;
BEGIN
  -- permissions 테이블에서 type이 'TRIAL'인 권한의 ID와 기간을 찾습니다.
  SELECT id, duration_seconds INTO trial_permission_id, trial_duration_seconds
  FROM public.permissions
  WHERE type = 'TRIAL'
  LIMIT 1;

  -- 'TRIAL' 권한이 존재할 경우에만 실행합니다.
  IF trial_permission_id IS NOT NULL THEN
    -- user_permissions 테이블에 새로운 사용자의 무료 체험 권한을 추가합니다.
    INSERT INTO public.user_permissions (user_id, permission_id, expires_at)
    VALUES (
      NEW.id, -- 방금 가입한 사용자의 ID
      trial_permission_id, -- 위에서 찾은 TRIAL 권한의 ID
      now() + (trial_duration_seconds * interval '1 second') -- 현재시간 + 권한의 유효시간
    );
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 8. auth.users 테이블에 새로운 사용자가 추가될 때마다 위 함수를 실행하는 트리거를 생성합니다.
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();