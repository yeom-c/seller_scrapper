-- 1. 커스텀 ENUM 타입 생성
CREATE TYPE public.permission_type AS ENUM (
  'TRIAL', -- 회원가입시 기본 제공되는 무료 체험
  'PAID'   -- 유료 결제 플랜
);
COMMENT ON TYPE public.permission_type IS '권한의 종류를 나타내는 ENUM 타입입니다.';

-- 2. workflows 테이블 생성
CREATE TABLE public.workflows (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL,
  workflow_json jsonb NOT NULL,
  CONSTRAINT workflows_pkey PRIMARY KEY (id)
);

-- 3. permissions 테이블 생성 (type 컬럼 적용)
CREATE TABLE public.permissions (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL,
  type public.permission_type NOT NULL,
  duration_seconds integer NOT NULL,
  workflow_id uuid NOT NULL,
  CONSTRAINT permissions_pkey PRIMARY KEY (id),
  CONSTRAINT permissions_workflow_id_fkey FOREIGN KEY (workflow_id) REFERENCES public.workflows(id) ON DELETE CASCADE
);
COMMENT ON COLUMN public.permissions.type IS '권한의 타입을 나타냅니다 (TRIAL, PAID 등).';

-- 4. user_permissions 테이블 생성
CREATE TABLE public.user_permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL,
  permission_id uuid NOT NULL,
  expires_at timestamptz NOT NULL,
  CONSTRAINT user_permissions_pkey PRIMARY KEY (id),
  CONSTRAINT user_permissions_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE,
  CONSTRAINT user_permissions_permission_id_fkey FOREIGN KEY (permission_id) REFERENCES public.permissions(id) ON DELETE CASCADE
);

